// npm run export:seed [-- --tz <IANA time zone>] [--out <folder>]
//
// Writes the backend seed: the demo backend's starting data as a PostgreSQL database (schema.sql, seed.sql),
// one CSV and one JSON file per table, a manifest and a data dictionary — in backend-seed/ by default.
//
// The seed's times are wall-clock times ("Layla signed in at 07:52 on 24 June"), so they are written for
// one time zone: Asia/Kolkata unless --tz names another.
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { dataDictionary, describeViews, idCounters, manifest, schemaSql, seedSql, tableCsv, tableJson, tableSummary } from "./writers.js";

const DEFAULT_TIME_ZONE = "Asia/Kolkata";

function readArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 1) {
    const [flag, inline] = argv[i].split("=");
    if (!["--tz", "--out"].includes(flag)) throw new Error(`Unknown option ${argv[i]}. Use --tz <time zone> and --out <folder>.`);
    args[flag.slice(2)] = inline ?? argv[++i];
    if (!args[flag.slice(2)]) throw new Error(`${flag} needs a value.`);
  }
  return args;
}

let args;
try {
  args = readArgs(process.argv.slice(2));
  Intl.DateTimeFormat("en-US", { timeZone: args.tz ?? DEFAULT_TIME_ZONE });
} catch (error) {
  console.error(error instanceof RangeError ? `Unknown time zone "${args?.tz}". Use an IANA name like Asia/Kolkata.` : error.message);
  process.exit(1);
}
const timeZone = args.tz ?? DEFAULT_TIME_ZONE;
// Before any seed module runs: the seed turns its wall-clock times into timestamps in this zone
process.env.TZ = timeZone;

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const out = path.resolve(root, args.out ?? "backend-seed");

const { createServer } = await import("vite");
const vite = await createServer({
  root,
  configFile: false,
  logLevel: "error",
  appType: "custom",
  server: { middlewareMode: true, hmr: false, watch: null },
  optimizeDeps: { noDiscovery: true, include: [] },
});

try {
  // The demo backend's database, freshly built from src/data/seed.js
  const { db, resetForTests } = await vite.ssrLoadModule("/src/services/mock/db.js");
  const { buildTables } = await vite.ssrLoadModule("/scripts/backend-seed/tables.js");
  resetForTests();
  const tables = buildTables(db());

  const views = await readFile(path.join(here, "views.sql"), "utf8");
  const template = await readFile(path.join(here, "README.template.md"), "utf8");
  const dictionaryIntro = await readFile(path.join(here, "DATA_DICTIONARY.intro.md"), "utf8");
  const totalRows = tables.reduce((sum, t) => sum + t.rows.length, 0);
  const header = (what) =>
    [
      `-- DemandIQ backend seed: ${what}`,
      "-- Generated by `npm run export:seed` from src/data/seed.js (the demo backend's starting data).",
      `-- Times are the demo's wall-clock times in ${timeZone}. Don't edit by hand: change the seed and export again.`,
      "-- Load with: psql -v ON_ERROR_STOP=1 -d demandiq -f schema.sql -f seed.sql",
      "",
    ].join("\n");

  await mkdir(out, { recursive: true });
  for (const folder of ["csv", "json"]) {
    await rm(path.join(out, folder), { recursive: true, force: true });
    await mkdir(path.join(out, folder));
  }
  const files = {
    "schema.sql": schemaSql(tables, views, header(`${tables.length} tables, their keys and checks, ID sequences and views (PostgreSQL 12+)`)),
    "seed.sql": seedSql(tables, header(`${totalRows.toLocaleString("en-US")} rows in ${tables.length} tables, in load order`)),
    "manifest.json": manifest(tables, { generatedBy: "npm run export:seed", source: "src/data/seed.js", timeZone, totalRows }),
    "DATA_DICTIONARY.md": dataDictionary(tables, describeViews(views), dictionaryIntro),
    "README.md": fillReadme(template, { tables, views, timeZone, totalRows }),
  };
  for (const t of tables) {
    files[`csv/${t.name}.csv`] = tableCsv(t);
    files[`json/${t.name}.json`] = tableJson(t);
  }
  for (const [name, text] of Object.entries(files)) await writeFile(path.join(out, name), text, "utf8");

  const width = Math.max(...tables.map((t) => t.name.length));
  console.log(`Backend seed → ${path.relative(root, out) || "."}/ (times in ${timeZone})`);
  for (const t of tables) console.log(`  ${t.name.padEnd(width)}  ${String(t.rows.length).padStart(5)} rows`);
  console.log(`  ${"total".padEnd(width)}  ${String(totalRows).padStart(5)} rows in ${tables.length} tables`);
  console.log("Load it: psql -v ON_ERROR_STOP=1 -d demandiq -f schema.sql -f seed.sql (see README.md there)");
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
} finally {
  await vite.close();
}

/** README.md from README.template.md: {{name}} placeholders filled from the tables. */
function fillReadme(template, { tables, views, timeZone: zone, totalRows }) {
  const find = (name) => tables.find((t) => t.name === name);
  const users = find("users").rows;
  const roleNames = new Map(find("roles").rows.map((r) => [r.role_id, r.name]));
  const signIn = { Active: "Yes", "Pending activation": "No — 403 `account_pending`", Inactive: "No — 403 `account_inactive`" };
  const accounts = [
    "| User ID | Name | Email | Password | Role | Status | Can sign in |",
    "|---|---|---|---|---|---|---|",
    ...users.map(
      (u) =>
        `| ${u.user_id} | ${u.name} | ${u.email} | \`${u.password_hash.plain}\` | ${u.role_id} ${roleNames.get(u.role_id)} | ${u.status} | ${signIn[u.status]} |`,
    ),
  ].join("\n");
  const processing = find("reports").rows.filter((r) => r.status === "Processing");
  const values = {
    TOTAL_ROWS: totalRows.toLocaleString("en-US"),
    TABLE_COUNT: String(tables.length),
    TIME_ZONE: zone,
    TABLE_SUMMARY: tableSummary(tables),
    VIEWS: describeViews(views)
      .map((v) => `- **\`${v.name}\`** — ${v.about}`)
      .join("\n"),
    NEXT_IDS: idCounters(tables)
      .map((c) => `\`${c.table}\` ${c.next}`)
      .join(", "),
    ACCOUNTS: accounts,
    PROCESSING_REPORTS: processing.map((r) => r.report_id).join(", "),
    PROCESSING_COUNT: String(processing.length),
    VIEW_COUNT: String(describeViews(views).length),
  };
  const filled = template.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    if (!(key in values)) throw new Error(`README.template.md: unknown placeholder ${match}`);
    return values[key];
  });
  return filled;
}
